import type { SiteGroup, SiteId } from './types.ts';

export type SiteDef = {
  id: SiteId;
  group: SiteGroup;
  /** Nombre completo («Pliegue tríceps»). */
  label: string;
  /** Nombre corto para listas y para la voz («Tríceps»). */
  short: string;
  unit: 'kg' | 'cm' | 'mm';
  /** Decimales con los que se anota (0,1 en todos los puntos ISAK). */
  decimals: number;
  /** Tolerancia ISAK entre la 1.ª y la 2.ª lectura, en %: 5 en pliegues, 1 en el resto. */
  tolerancePct: number;
  /** Fuera de este rango el valor no se acepta (error seguro). */
  hard: [number, number];
  /** Fuera de este rango se pide confirmar («valor poco habitual»). */
  soft: [number, number];
  /** Dígitos máximos de la parte entera en el teclado. */
  maxInt: number;
  /** Indicación de una línea (punto anatómico y técnica). */
  howTo: string;
  /** Medidas que apenas cambian entre sesiones (admiten «Repetir anterior»). */
  stable: boolean;
  /** Punto que no es del perfil ISAK restringido (solo Jackson-Pollock). */
  extra?: boolean;
};

